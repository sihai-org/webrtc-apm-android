#!/usr/bin/env python3
"""Extract the pinned public config fields and generate Kotlin/JNI mappings.

The schema is a reviewable projection of upstream headers, not an independent
configuration definition. Unsupported declarations fail generation.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
HEADERS = {
    'ApmConfig': ('api/audio/audio_processing.h', 'Config', 'webrtc::AudioProcessing::Config'),
    'Aec3Config': ('api/audio/echo_canceller3_config.h', 'EchoCanceller3Config', 'webrtc::EchoCanceller3Config'),
}


def closing(text, start):
    depth = 1
    for index in range(start + 1, len(text)):
        depth += (text[index] == '{') - (text[index] == '}')
        if depth == 0:
            return index
    raise ValueError('Unbalanced upstream declaration')


def parse_body(text, parent_types=None):
    types = dict(parent_types or {})
    fields = []
    index = 0
    while index < len(text):
        if text[index].isspace() or text[index] == ';':
            index += 1
            continue
        semi = text.find(';', index)
        brace = text.find('{', index)
        if brace != -1 and (semi == -1 or brace < semi):
            prefix = text[index:brace].strip()
            end = closing(text, brace)
            declaration = re.fullmatch(r'(struct|enum(?: class)?)\s+(?:RTC_EXPORT\s+)?(\w+)', prefix)
            if declaration:
                kind, name = declaration.groups()
                if kind == 'struct':
                    node = {'fields': parse_body(text[brace+1:end], types)}
                else:
                    entries = [entry.strip() for entry in text[brace+1:end].split(',') if entry.strip()]
                    if not all(re.fullmatch(r'\w+', entry) for entry in entries):
                        raise ValueError('Review explicit enum values: ' + prefix)
                    node = {'enum': entries}
                types[name] = node
                semi = text.index(';', end)
                suffix = text[end+1:semi].strip()
                if suffix:
                    field = re.match(r'(\w+)(?:\s*=.*)?$', suffix, re.S)
                    if not field:
                        raise ValueError('Unsupported struct member: ' + suffix)
                    fields.append({'name': field[1], **node})
                index = semi + 1
                continue
            # Skip inline member functions, not aggregate field initializers.
            if '(' in prefix and not re.match(r'^\w+\s+\w+\s*=', prefix):
                index = end + 1
                continue
            # A field with a designated initializer is consumed through its ';'.
            semi = text.index(';', end)
        if semi == -1:
            if text[index:].strip():
                raise ValueError('Unparsed declaration: ' + text[index:])
            break
        statement = text[index:semi].strip()
        index = semi + 1
        before_equal = statement.split('=', 1)[0]
        if '(' in before_equal or re.search(r'\boperator\b', statement) or statement.startswith(('static ', 'friend ')):
            continue
        match = re.fullmatch(r'(bool|int|float|size_t|\w+)\s+(\w+)(?:\s*=.*)?', statement, re.S)
        if not match:
            raise ValueError('Unsupported field declaration: ' + statement)
        kind, name = match.groups()
        if kind in types:
            fields.append({'name': name, **types[kind]})
        elif kind in ('bool', 'int', 'float', 'size_t'):
            fields.append({'name': name, 'type': kind})
        else:
            raise ValueError('Unknown field type: ' + kind)
    return fields


def extract(path, root_name):
    text = re.sub(r'/\*.*?\*/|//[^\n]*', '', path.read_text(), flags=re.S)
    match = re.search(r'struct\s+(?:RTC_EXPORT\s+)?' + root_name + r'\s*\{', text)
    if match is None:
        raise ValueError('Missing ' + root_name)
    start = match.end() - 1
    return parse_body(text[start+1:closing(text, start)])


def camel(name, upper=False):
    parts = name.split('_')
    return (parts[0][:1].upper() + parts[0][1:] if upper else parts[0]) + ''.join(p[:1].upper() + p[1:] for p in parts[1:])


def leaves(fields, prefix=''):
    for field in fields:
        name = prefix + field['name']
        if 'fields' in field:
            yield from leaves(field['fields'], name + '.')
        else:
            yield name, field


def kotlin(class_name, fields):
    kind = 0 if class_name == 'ApmConfig' else 1
    flat = list(leaves(fields))
    indices = {name: index for index, (name, _) in enumerate(flat)}
    source = ['// Generated by scripts/generate_config.py. Do not edit.',
              'package org.sihai.apm', '',
              f'class {class_name} internal constructor(internal val values: DoubleArray) {{',
              f'    constructor() : this(NativeBridge.defaultConfig({kind}))',
              f'    fun copy(): {class_name} = {class_name}(values.copyOf())']
    if kind == 1:
        source += ['    companion object {', '        fun multichannelDefaults(): Aec3Config = Aec3Config(NativeBridge.defaultConfig(2))', '    }']
    groups = []

    def emit(members, prefix, indent):
        nonlocal source
        for field in members:
            path = prefix + field['name']
            prop = camel(field['name'])
            if 'fields' in field:
                cls = ''.join(camel(p, True) for p in path.split('.'))
                source.append(f'{indent}val {prop}: {cls} = {cls}(values)')
                groups.append((cls, field['fields'], path + '.'))
                continue
            idx = indices[path]
            if 'enum' in field:
                enum_name = camel(field['name'], True)
                values = [camel(v[1:] if v.startswith('k') else v, True) for v in field['enum']]
                source.append(f'{indent}enum class {enum_name} {{ ' + ', '.join(values) + ' }')
                typ = enum_name
                getter = f'{enum_name}.entries[values[{idx}].toInt()]'
                setter = 'value.ordinal.toDouble()'
                check = ''
            else:
                typ = {'bool': 'Boolean', 'float': 'Float', 'int': 'Int', 'size_t': 'Long'}[field['type']]
                getter = f'values[{idx}]' + {'bool': ' != 0.0', 'float': '.toFloat()', 'int': '.toInt()', 'size_t': '.toLong()'}[field['type']]
                setter = 'if (value) 1.0 else 0.0' if typ == 'Boolean' else 'value.toDouble()'
                check = 'require(value.isFinite()); ' if typ == 'Float' else ('require(value in 0..4294967295L); ' if typ == 'Long' else '')
            source += [f'{indent}/** Upstream `{path}`. */', f'{indent}var {prop}: {typ}',
                       f'{indent}    get() = {getter}', f'{indent}    set(value) {{ {check}values[{idx}] = {setter} }}']
    emit(fields, '', '    ')
    i = 0
    while i < len(groups):
        cls, members, prefix = groups[i]
        source.append(f'    class {cls} internal constructor(private val values: DoubleArray) {{')
        emit(members, prefix, '        ')
        source.append('    }')
        i += 1
    source.append('}')
    return '\n'.join(source) + '\n'


def cpp(class_name, fields, native_type):
    flat = list(leaves(fields))
    out = [f'constexpr size_t k{class_name}Size = {len(flat)};',
           f'inline std::vector<double> Encode(const {native_type}& c) {{', '  return {']
    out += [f'    static_cast<double>(c.{path}),' for path, _ in flat]
    out += ['  };', '}', f'inline bool Decode(const std::vector<double>& v, {native_type}* c) {{',
            f'  if (v.size() != k{class_name}Size) return false;']
    for index, (path, field) in enumerate(flat):
        cond = f'!std::isfinite(v[{index}])'
        if 'enum' in field or field.get('type') != 'float':
            low, high = (-2147483648, 2147483647)
            if 'enum' in field: low, high = 0, len(field['enum']) - 1
            elif field['type'] == 'bool': low, high = 0, 1
            elif field['type'] == 'size_t': low, high = 0, 4294967295
            cond += f' || std::floor(v[{index}]) != v[{index}] || v[{index}] < {low}.0 || v[{index}] > {high}.0'
        out += [f'  if ({cond}) return false;',
                f'  c->{path} = static_cast<decltype(c->{path})>(v[{index}]);']
    out += ['  return true;', '}']
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--upstream', type=Path, help='Pinned WebRTC src directory for coverage verification')
    parser.add_argument('--update-schema', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.update_schema and args.upstream is None:
        parser.error('--update-schema requires --upstream')
    native = ['// Generated by scripts/generate_config.py. Do not edit.', '#pragma once',
              '#include <cmath>', '#include <vector>', '#include "api/audio/audio_processing.h"',
              '#include "api/audio/echo_canceller3_config.h"', 'namespace apm_android {']
    rows = ['# 配置字段映射（生成）', '', '上游字段、Android 属性和 native 数组位置由同一 schema 生成。默认值直接从上游 C++ 配置读取。', '', '| 类型 | 上游字段 | 值类型 |', '| --- | --- | --- |']
    outputs = {}
    for cls, (header, struct, native_type) in HEADERS.items():
        schema = ROOT / 'schema' / (cls + '.json')
        if args.upstream:
            extracted = extract(args.upstream / header, struct)
            if args.update_schema:
                schema.parent.mkdir(exist_ok=True)
                schema.write_text(json.dumps(extracted, indent=2) + '\n')
            elif extracted != json.loads(schema.read_text()):
                raise SystemExit(f'Upstream field coverage drift: {header}')
        fields = json.loads(schema.read_text())
        outputs[ROOT / f'apm/src/main/kotlin/org/sihai/apm/{cls}.kt'] = kotlin(cls, fields)
        native.append(cpp(cls, fields, native_type))
        flat = list(leaves(fields))
        print(f'{cls}: {len(flat)} mapped fields')
        rows += [f'| {cls} | `{path}` | ' + ('enum: ' + ', '.join(f['enum']) if 'enum' in f else f['type']) + ' |' for path, f in flat]
    native.append('}  // namespace apm_android')
    outputs[ROOT / 'native/config_generated.h'] = '\n'.join(native) + '\n'
    outputs[ROOT / 'docs/config-fields.md'] = '\n'.join(rows) + '\n'
    revision = json.loads((ROOT / 'upstream.lock.json').read_text())['webrtc_revision']
    outputs[ROOT / 'native/upstream_generated.h'] = ('// Generated. Do not edit.\n#pragma once\n'
        f'#define APM_UPSTREAM_REVISION "{revision}"\n')
    for path, text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'Stale generated file: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)


if __name__ == '__main__':
    main()
